import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { parseArgs } from 'node:util';

import { manifestSchema, type Manifest, type ManifestProject } from '@the40thieves/schemas';

import { repoRoot } from './lib/policy.ts';

/**
 * The org profile README (P2-10): `github.com/The-40-Thieves` is rendered from the hub
 * manifest, never written by hand. Markdown only; the images are the hub's own `/og/*.svg`,
 * linked by content hash so GitHub Camo fetches a changed card under a new URL.
 *
 * `--out <file>` writes the Markdown locally. `--publish` compares it with
 * `The-40-Thieves/.github:profile/README.md` and commits through the App token in
 * `GITHUB_TOKEN` only when the body (everything but the "Last updated" trailer) differs, so
 * two deploys with no content change produce no commit.
 */

export const ORG = 'The-40-Thieves';
export const README_REPO = `${ORG}/.github`;
export const README_PATH = 'profile/README.md';
export const DIST = 'apps/hub/dist/client';

export interface CardHashes {
  banner: string;
  /** Slug to hash, one per project with a page. */
  cards: Record<string, string>;
}

const TRAILER =
  /^Last updated \d{4}-\d{2}-\d{2} from the40thieves\.dev at commit (?:[0-9a-f]{7}|unknown)[.].*$/m;

function cell(value: string): string {
  return value.replaceAll('|', '\\|').replaceAll('\n', ' ');
}

function releaseCell(project: ManifestProject): string {
  if (!project.release) return 'none yet';
  return `[${cell(project.release.tag)}](${project.release.url}) ${project.release.published_at.slice(0, 10)}`;
}

function installCell(project: ManifestProject): string {
  return project.install.shell
    ? `\`${cell(project.install.shell.replaceAll('`', ''))}\``
    : 'see the project page';
}

export function renderOrgReadme(
  manifest: Manifest,
  hashes: CardHashes,
  generatedAt: string,
): string {
  const site = manifest.site;
  const listed = manifest.projects.filter((project) => project.page !== null);
  const unlisted = manifest.projects.filter((project) => project.page === null);
  for (const project of listed) {
    if (!hashes.cards[project.slug]) throw new Error(`no card hash for ${project.slug}`);
  }
  const toolCounts = new Map<string, number>();
  for (const tool of manifest.tools) {
    toolCounts.set(tool.project, (toolCounts.get(tool.project) ?? 0) + 1);
  }
  const withTools = manifest.tools.length > 0;

  const header = withTools
    ? '| Project | What it is | Latest release | Tools | Install |\n| --- | --- | --- | --- | --- |'
    : '| Project | What it is | Latest release | Install |\n| --- | --- | --- | --- |';
  const rows = listed.map((project) => {
    const cells = [
      `[${cell(project.name)}](${site}${project.page ?? '/'})`,
      cell(project.tagline),
      releaseCell(project),
    ];
    if (withTools) cells.push(String(toolCounts.get(project.slug) ?? 0));
    cells.push(installCell(project));
    return `| ${cells.join(' | ')} |`;
  });

  const lines = [
    `[![The 40 Thieves. Tools first.](${site}/og/banner.svg?v=${hashes.banner})](${site})`,
    '',
    'Open-source developer tools, each with one measured claim and a one-line install.',
    '',
    ...listed.map(
      (project) =>
        `[![${cell(project.name)}](${site}/og/card/${project.slug}.svg?v=${hashes.cards[project.slug] ?? ''})](${site}${project.page ?? '/'})`,
    ),
    '',
    '## Projects',
    '',
    header,
    ...rows,
    '',
    `Product pages, install snippets for each client and the release notes live at [${site.replace('https://', '')}](${site}). ` +
      `Releases feed: ${site}/releases.xml. Machine-readable index: ${site}/manifest.json.`,
  ];
  if (unlisted.length > 0) {
    lines.push(
      '',
      '## Also on GitHub',
      '',
      ...unlisted.map((project) => `- [${cell(project.name)}](${project.repo})`),
    );
  }
  lines.push(
    '',
    '## Contributing',
    '',
    'Contributions are welcome on every project: [CONTRIBUTING](../CONTRIBUTING.md). ' +
      'Security reports: [SECURITY](../SECURITY.md). Conduct: [CODE_OF_CONDUCT](../CODE_OF_CONDUCT.md).',
    '',
    `Last updated ${generatedAt.slice(0, 10)} from the40thieves.dev at commit ${(manifest.commit ?? 'unknown').slice(0, 7)}. ` +
      'This file is generated by the hub deploy; edits here are overwritten.',
    '',
  );
  return lines.join('\n');
}

/** The README without its trailer line, normalised, for change detection. */
export function bodyOf(markdown: string): string {
  return markdown.replaceAll('\r\n', '\n').replace(TRAILER, '').trim();
}

export function readmeChanged(rendered: string, existing: string | null): boolean {
  return existing === null || bodyOf(rendered) !== bodyOf(existing);
}

export function contentHash(content: string): string {
  return createHash('sha256').update(content).digest('hex').slice(0, 8);
}

/** Hashes of the SVGs the build emitted under `dist/og`. */
export function readCardHashes(dist: string = resolve(repoRoot, DIST)): CardHashes {
  const banner = readFileSync(join(dist, 'og', 'banner.svg'), 'utf8');
  const cards: Record<string, string> = {};
  const dir = join(dist, 'og', 'card');
  if (existsSync(dir)) {
    for (const file of readdirSync(dir)) {
      if (!file.endsWith('.svg')) continue;
      cards[file.slice(0, -'.svg'.length)] = contentHash(readFileSync(join(dir, file), 'utf8'));
    }
  }
  return { banner: contentHash(banner), cards };
}

export function readManifest(dist: string = resolve(repoRoot, DIST)): Manifest {
  return manifestSchema.parse(JSON.parse(readFileSync(join(dist, 'manifest.json'), 'utf8')));
}

interface ExistingFile {
  sha: string;
  content: string;
}

interface GithubInit {
  method?: string;
  body?: string;
  headers?: Record<string, string>;
}

async function github(path: string, token: string, init: GithubInit = {}): Promise<Response> {
  return fetch(`https://api.github.com/${path}`, {
    ...init,
    headers: {
      Accept: 'application/vnd.github+json',
      Authorization: `Bearer ${token}`,
      'User-Agent': 'the40thieves-hub-deploy',
      'X-GitHub-Api-Version': '2022-11-28',
      ...(init.headers ?? {}),
    },
  });
}

async function readExisting(token: string): Promise<ExistingFile | null> {
  const response = await github(`repos/${README_REPO}/contents/${README_PATH}`, token);
  if (response.status === 404) return null;
  if (!response.ok) throw new Error(`GET ${README_PATH}: ${String(response.status)}`);
  const body = (await response.json()) as { sha: string; content: string; encoding: string };
  if (body.encoding !== 'base64') throw new Error(`unexpected encoding ${body.encoding}`);
  return { sha: body.sha, content: Buffer.from(body.content, 'base64').toString('utf8') };
}

async function publish(rendered: string, commit: string | null, token: string): Promise<void> {
  const existing = await readExisting(token);
  if (!readmeChanged(rendered, existing?.content ?? null)) {
    console.log(`org README unchanged; no commit to ${README_REPO}`);
    return;
  }
  const response = await github(`repos/${README_REPO}/contents/${README_PATH}`, token, {
    method: 'PUT',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      message: `org README: regenerated from the hub manifest at ${(commit ?? 'unknown').slice(0, 7)}`,
      content: Buffer.from(rendered, 'utf8').toString('base64'),
      ...(existing ? { sha: existing.sha } : {}),
    }),
  });
  if (!response.ok) {
    throw new Error(`PUT ${README_PATH}: ${String(response.status)} ${await response.text()}`);
  }
  const result = (await response.json()) as { commit?: { sha?: string } };
  console.log(`org README committed to ${README_REPO}: ${result.commit?.sha?.slice(0, 7) ?? '?'}`);
}

async function main(): Promise<void> {
  const { values } = parseArgs({
    options: {
      out: { type: 'string' },
      publish: { type: 'boolean', default: false },
      dist: { type: 'string', default: DIST },
    },
  });
  const dist = resolve(repoRoot, values.dist);
  const manifest = readManifest(dist);
  const rendered = renderOrgReadme(manifest, readCardHashes(dist), new Date().toISOString());
  if (values.out) {
    writeFileSync(resolve(repoRoot, values.out), rendered);
    console.log(`wrote ${values.out}`);
  }
  if (values.publish) {
    const token = process.env['GITHUB_TOKEN'];
    if (!token) throw new Error('GITHUB_TOKEN is not set');
    await publish(rendered, manifest.commit, token);
  }
  if (!values.out && !values.publish) process.stdout.write(rendered);
}

if (import.meta.main) {
  await main();
}
